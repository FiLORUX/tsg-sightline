// Scan commit messages and changed files for AI attribution traces.
//
// Why this lives in the repository: the shared scanner sits in a private
// repository, and GitHub does not allow a public repository to call a private
// reusable workflow, so the check failed before it started. A repository-local
// script runs identically on a workstation, in a hook and in CI, with no
// cross-repository dependency. The patterns mirror the shared scanner.
//
// Usage: node tools/scan-ai-traces.mjs <base-sha> <head-sha>
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';

const COMMIT_PATTERNS = [
  /Co-authored-by:.*(Claude|ChatGPT|Copilot|OpenAI|Anthropic|Gemini|Cursor|AI Assistant)/i,
  /Generated by (Claude|ChatGPT|AI|LLM|Copilot)/i,
  /AI-assisted/i, /AI-generated/i, /with assistance from (Claude|ChatGPT|AI)/i,
];
const FILE_PATTERNS = [
  /Generated by (Claude|ChatGPT|Copilot|AI|LLM)/i, /AI-generated/i, /LLM-generated/i,
  /Written by (AI|Claude)/i, /Created by (AI|Claude)/i,
  /with assistance from (Claude|ChatGPT)/i, /assisted by (Claude|AI)/i,
  /Anthropic Claude/i, /OpenAI ChatGPT/i, /GitHub Copilot generated/i,
  /\/\/ AI:/, /# AI:/, /<!-- AI:/,
];
const SCAN_EXTENSIONS = /\.(html|css|js|mjs|ts|jsx|tsx|json|md|txt|py|sh|yml|yaml|xml)$/;
// This file necessarily contains the patterns it searches for.
const SKIP = /^(node_modules|vendor|dist|build|\.git|llm-context|\.claude|\.github)\/|^tools\/scan-ai-traces\.mjs$/;

const [base, head] = process.argv.slice(2);
if (!base || !head) { console.error('Usage: scan-ai-traces.mjs <base-sha> <head-sha>'); process.exit(2); }
const git = (...args) => execFileSync('git', args, { encoding: 'utf8' });

let failures = 0;
for (const sha of git('log', '--format=%H', `${base}..${head}`).split('\n').filter(Boolean)) {
  const message = git('log', '--format=%B', '-1', sha);
  for (const pattern of COMMIT_PATTERNS) {
    if (pattern.test(message)) { console.error(`Commit ${sha.slice(0, 7)}: AI trace (${pattern})`); failures++; }
  }
}
for (const file of git('diff', '--name-only', '--diff-filter=d', `${base}..${head}`).split('\n').filter(Boolean)) {
  if (!SCAN_EXTENSIONS.test(file) || SKIP.test(file) || !existsSync(file)) continue;
  const text = readFileSync(file, 'utf8');
  const hit = FILE_PATTERNS.find((pattern) => pattern.test(text));
  if (hit) { console.error(`${file}: AI trace (${hit})`); failures++; }
}
if (failures) { console.error(`${failures} AI trace(s) found`); process.exit(1); }
console.log('No AI traces found');
